"""Bake a 16x16 1bpp CJK font header for the firmware.

The device display can only draw what is in the font blob. The model can only
emit characters that appear in the training corpus (the BPE vocab was trained on
it), so the corpus is the character set: every hanzi plus every non-ASCII
punctuation mark, plus printable ASCII.

  uv run --no-project --with pillow python research/zh/gen_cjk_font.py

Output: firmware/esp32_tinystories/generated/cjk_font.h
  CJK_CHARS  sorted codepoints (uint16), binary-searched on device
  CJK_BITS   one 16x16 1bpp glyph per codepoint, 32 bytes, MSB = leftmost pixel
  CJK_COUNT  number of glyphs

Run it again whenever the corpus changes; the firmware's display path is
ASCII-only if a codepoint is missing.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CORPUS = os.path.join(ROOT, "data", "zh", "raw", "corpus.txt")
OUT = os.path.join(ROOT, "firmware", "esp32_tinystories", "generated", "cjk_font.h")

W = H = 16
STRIDE = W // 8  # 2 bytes per row

# SimSun keeps a hand-tuned bitmap for 16px; the outline rasteriser reproduces
# that look far better than a modern UI face at this size.
FONT_CANDIDATES = [
    (r"C:\Windows\Fonts\simsun.ttc", 0),
    (r"C:\Windows\Fonts\msyh.ttc", 0),
    (r"C:\Windows\Fonts\simhei.ttf", 0),
]


def pick_font():
    for path, index in FONT_CANDIDATES:
        if os.path.exists(path):
            return ImageFont.truetype(path, W, index=index), path
    sys.exit("no CJK font found; edit FONT_CANDIDATES")


def collect_chars():
    """BMP only: CJK_CHARS is uint16, so astral-plane characters (emoji that
    slipped into the corpus) cannot be represented and would corrupt the
    binary-search ordering. U+FFFD is a decode artefact, not a real glyph."""
    chars = set(chr(c) for c in range(32, 127))
    skipped = 0
    with open(CORPUS, encoding="utf-8") as f:
        for line in f:
            for ch in line:
                cp = ord(ch)
                if 127 < cp <= 0xFFFF and ch != "\ufffd":
                    chars.add(ch)
                elif cp > 0xFFFF:
                    skipped += 1
    if skipped:
        print(f"skipped {skipped} astral-plane chars")
    return sorted(chars, key=ord)


def render(font, ch):
    """One glyph as 32 bytes. Threshold at mid-grey: the panel is 1bpp."""
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), ch, font=font, fill=255, anchor="lt")
    px = img.load()
    out = bytearray(STRIDE * H)
    for y in range(H):
        for x in range(W):
            if px[x, y] >= 110:
                out[y * STRIDE + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(out)


def preview(font, chars, path):
    """Contact sheet of the first 256 glyphs, to eyeball the rasteriser."""
    cols, rows = 32, 8
    img = Image.new("L", (cols * W, rows * H + rows * 2), 0)
    d = ImageDraw.Draw(img)
    for i, ch in enumerate(chars[: cols * rows]):
        x = (i % cols) * W
        y = (i // cols) * (H + 2)
        d.text((x, y), ch, font=font, fill=255, anchor="lt")
    img.save(path)


def main():
    font, path = pick_font()
    chars = collect_chars()
    print(f"font {path}: {len(chars)} glyphs -> {len(chars) * STRIDE * H / 1024:.0f} KB")

    blobs = [render(font, ch) for ch in chars]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by research/zh/gen_cjk_font.py -- do not edit.\n")
        f.write(f"// {W}x{H} 1bpp, {len(chars)} glyphs, "
                f"{len(chars) * STRIDE * H / 1024:.0f} KB. Sorted by codepoint.\n")
        f.write("#ifndef CJK_FONT_H_INCLUDED\n#define CJK_FONT_H_INCLUDED\n"
                "#include <stdint.h>\n\n")
        f.write(f"#define CJK_FONT_W {W}\n#define CJK_FONT_H {H}\n")
        f.write(f"#define CJK_COUNT {len(chars)}\n\n")

        f.write("static const uint16_t CJK_CHARS[CJK_COUNT] = {\n")
        for i in range(0, len(chars), 12):
            row = ", ".join(f"0x{ord(c):04X}" for c in chars[i:i + 12])
            f.write("  " + row + ",\n")
        f.write("};\n\n")

        f.write("static const uint8_t CJK_BITS[CJK_COUNT * 32] = {\n")
        for i, blob in enumerate(blobs):
            body = ",".join(f"0x{b:02X}" for b in blob)
            # Hex, not the character: a backslash glyph would comment out the
            # next line, and non-ASCII in comments trips older toolchains.
            f.write(f"  {body},  // U+{ord(chars[i]):04X}\n")
        f.write("};\n\n#endif  // CJK_FONT_H_INCLUDED\n")

    preview(font, chars, os.path.join(ROOT, "artifacts", "zh", "cjk_preview.png"))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
