"""Emits the BPE *encoder* tables so the board can tokenize Chinese itself.

The existing generate_vocab.py exports the decode side (id -> bytes), which is
all the firmware needed while the prompt was baked in. To accept an arbitrary
opening from an HTTP request the board also needs the merge list: byte-level
BPE, 16384 tokens, 16127 merges. Storing the merge pairs as (token id, token id)
and sorting them lets the encoder find a pair's rank with a binary search, about
130 KB of flash for the three arrays.

    python firmware/esp32_tinystories/tools/generate_bpe_encode.py \
        --tokenizer artifacts/zh/tokenizer.json
"""

import argparse
import json
from pathlib import Path

GPT2_END = 0x100


def bytes_to_unicode():
    """The GPT-2 byte <-> printable unicode table ByteLevel uses."""
    bs = (list(range(ord("!"), ord("~") + 1))
          + list(range(ord("¡"), ord("¬") + 1))
          + list(range(ord("®"), ord("ÿ") + 1)))
    cs = bs[:]
    n = 0
    for b in range(256):
        if b not in bs:
            bs.append(b)
            cs.append(GPT2_END + n)
            n += 1
    return dict(zip(bs, (chr(c) for c in cs)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tokenizer", required=True)
    ap.add_argument("--out", default=None,
                    help="default: generated/bpe_encode.h next to this sketch")
    args = ap.parse_args()

    data = json.loads(Path(args.tokenizer).read_text(encoding="utf-8"))
    if data["model"]["type"] != "BPE":
        raise SystemExit(f"expected a BPE tokenizer, got {data['model']['type']}")
    vocab = data["model"]["vocab"]
    merges = data["model"]["merges"]
    if len(merges) > 0xFFFF or len(vocab) > 0xFFFF:
        raise SystemExit("token ids must fit in uint16")

    b2u = bytes_to_unicode()
    byte_id = []
    for b in range(256):
        ch = b2u[b]
        if ch not in vocab:
            raise SystemExit(f"byte {b} ({ch!r}) is not in the vocabulary; "
                             f"is this tokenizer byte-level?")
        byte_id.append(vocab[ch])

    rows = []
    for rank, pair in enumerate(merges):
        a, b = pair
        if a + b not in vocab:
            raise SystemExit(f"merge {rank} ({a!r},{b!r}) has no vocabulary entry")
        if a not in vocab or b not in vocab:
            raise SystemExit(f"merge {rank} references an unknown token")
        key = (vocab[a] << 16) | vocab[b]
        rows.append((key, rank, vocab[a + b]))

    rows.sort(key=lambda r: r[0])
    if len({r[0] for r in rows}) != len(rows):
        raise SystemExit("duplicate merge keys after id mapping")

    out = Path(args.out) if args.out else (
        Path(__file__).resolve().parents[1] / "generated" / "bpe_encode.h")
    out.parent.mkdir(parents=True, exist_ok=True)

    def arr(name, ctype, values, per_line=16):
        lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
        for i in range(0, len(values), per_line):
            chunk = ", ".join(str(v) for v in values[i:i + per_line])
            lines.append("    " + chunk + ",")
        lines.append("};")
        return "\n".join(lines)

    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/generate_bpe_encode.py -- do not edit.\n")
        f.write(f"// tokenizer: {Path(args.tokenizer).name}  "
                f"vocab {len(vocab)}  merges {len(rows)}\n")
        f.write("#ifndef BPE_ENCODE_H\n#define BPE_ENCODE_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define BPE_MERGE_N {len(rows)}\n\n")
        f.write("// GPT-2 byte-level alphabet: raw UTF-8 byte -> token id.\n")
        f.write(arr("BPE_BYTE_ID", "uint16_t", byte_id) + "\n\n")
        f.write("// Merge table, sorted by (a << 16 | b). BPE_RANK is the merge\n"
                "// order, BPE_NEW the id the pair collapses to.\n")
        f.write(arr("BPE_KEY", "uint32_t", [r[0] for r in rows]) + "\n\n")
        f.write(arr("BPE_RANK", "uint16_t", [r[1] for r in rows]) + "\n\n")
        f.write(arr("BPE_NEW", "uint16_t", [r[2] for r in rows]) + "\n\n")
        f.write("#endif\n")

    print(f"{out}  merges={len(rows)}  bytes={out.stat().st_size}")


if __name__ == "__main__":
    main()
